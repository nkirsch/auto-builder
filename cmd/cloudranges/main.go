// Command cloudranges writes cloudranges.go: the IP ranges Google Cloud and
// AWS publish for their customers' machines. Readers don't browse from
// there; headless scanners do, with browser user agents that load assets.
//
//	go run ./cmd/cloudranges > cmd/builder/cloudranges.go && gofmt -l cmd
package main

import (
	"encoding/json"
	"fmt"
	"net/http"
	"net/netip"
	"os"
	"slices"
	"strings"
)

func main() {
	var gcp struct {
		Prefixes []struct {
			V4 string `json:"ipv4Prefix"`
			V6 string `json:"ipv6Prefix"`
		}
	}
	var aws struct {
		Prefixes []struct {
			V4 string `json:"ip_prefix"`
		}
		IPv6Prefixes []struct {
			V6 string `json:"ipv6_prefix"`
		} `json:"ipv6_prefixes"`
	}
	fetch("https://www.gstatic.com/ipranges/cloud.json", &gcp)
	fetch("https://ip-ranges.amazonaws.com/ip-ranges.json", &aws)
	var g, a []string
	for _, p := range gcp.Prefixes {
		g = append(g, p.V4+p.V6)
	}
	for _, p := range aws.Prefixes {
		a = append(a, p.V4)
	}
	for _, p := range aws.IPv6Prefixes {
		a = append(a, p.V6)
	}
	fmt.Print("// Code generated by go run ./cmd/cloudranges; DO NOT EDIT.\n\npackage main\n\n")
	fmt.Printf("const googleCloudRanges = `%s`\n\n", strings.Join(collapse(g), "\n"))
	fmt.Printf("const awsRanges = `%s`\n", strings.Join(collapse(a), "\n"))
}

func fetch(url string, v any) {
	resp, err := http.Get(url)
	if err == nil && resp.StatusCode != http.StatusOK {
		err = fmt.Errorf("%s", resp.Status)
	}
	if err == nil {
		err = json.NewDecoder(resp.Body).Decode(v)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, url+":", err)
		os.Exit(1)
	}
}

// collapse sorts prefixes, drops those inside another and merges sibling halves.
func collapse(in []string) []string {
	var ps []netip.Prefix
	for _, s := range in {
		if p, err := netip.ParsePrefix(s); err == nil {
			ps = append(ps, p.Masked())
		}
	}
	for {
		slices.SortFunc(ps, func(x, y netip.Prefix) int {
			if c := x.Addr().Compare(y.Addr()); c != 0 {
				return c
			}
			return x.Bits() - y.Bits()
		})
		var out []netip.Prefix
		merged := false
		for _, p := range ps {
			if n := len(out); n > 0 {
				last := out[n-1]
				if last.Overlaps(p) && last.Bits() <= p.Bits() {
					continue
				}
				if last.Bits() == p.Bits() && last.Bits() > 0 {
					parent, _ := last.Addr().Prefix(last.Bits() - 1)
					if parent.Contains(p.Addr()) && parent.Addr() == last.Addr() {
						out[n-1] = parent
						merged = true
						continue
					}
				}
			}
			out = append(out, p)
		}
		ps = out
		if !merged {
			break
		}
	}
	s := make([]string, len(ps))
	for i, p := range ps {
		s[i] = p.String()
	}
	return s
}
